/**
 * Hand-built coloring-page drawings for the animals the generic body plans in
 * animal-art.ts can't do justice (each has its own silhouette). Same style:
 * black round-cap outlines on white, drawn in a 240×150 box (ground ≈ y 140),
 * animals face left.
 */
const SW = 4.6;
const S = `fill="#fff" stroke="#111" stroke-width="${SW}" stroke-linejoin="round" stroke-linecap="round"`;
const SK = `fill="none" stroke="#111" stroke-width="${SW}" stroke-linejoin="round" stroke-linecap="round"`;
const f = (n: number) => Math.round(n * 10) / 10;
const p = (d: string) => `<path d="${d}" ${SK}/>`;
const P = (d: string, extra = "") => `<path d="${d}" ${S} ${extra}/>`;
const E = (cx: number, cy: number, rx: number, ry: number, rot = 0) =>
  `<ellipse cx="${f(cx)}" cy="${f(cy)}" rx="${f(rx)}" ry="${f(ry)}" ${S}${rot ? ` transform="rotate(${rot} ${f(cx)} ${f(cy)})"` : ""}/>`;
const C = (cx: number, cy: number, r: number) => `<circle cx="${f(cx)}" cy="${f(cy)}" r="${f(r)}" ${S}/>`;
const dot = (x: number, y: number, r = 2.8) => `<circle cx="${f(x)}" cy="${f(y)}" r="${r}" fill="#111"/>`;
const poly = (pts: number[][]) => `<polygon points="${pts.map(([x, y]) => `${f(x)},${f(y)}`).join(" ")}" ${S}/>`;
/** thick outlined tube along a path (black stroke under a white stroke) */
const tube = (d: string, w: number) =>
  `<path d="${d}" fill="none" stroke="#111" stroke-width="${w + SW}" stroke-linecap="round" stroke-linejoin="round"/>` +
  `<path d="${d}" fill="none" stroke="#fff" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"/>`;
/** neck that merges into the body: black pass first, body, then this white pass */
const tubeBlack = (d: string, w: number) => `<path d="${d}" fill="none" stroke="#111" stroke-width="${w + SW}" stroke-linecap="round" stroke-linejoin="round"/>`;
const tubeWhite = (d: string, w: number) => `<path d="${d}" fill="none" stroke="#fff" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"/>`;
/** fluffy union of circles with a single outer outline */
const cloud = (cs: number[][]) =>
  cs.map(([x, y, r]) => `<circle cx="${x}" cy="${y}" r="${f(r + SW / 2)}" fill="#111"/>`).join("") +
  cs.map(([x, y, r]) => `<circle cx="${x}" cy="${y}" r="${r}" fill="#fff"/>`).join("");
const G = 140;
const leg = (x: number, top: number, w: number, hoof = false, bot = G) =>
  `<rect x="${f(x)}" y="${top}" width="${w}" height="${bot - top}" rx="${f(w * 0.38)}" ${S}/>` + (hoof ? p(`M${x + 1},${bot - 6} h${w - 2}`) : "");

