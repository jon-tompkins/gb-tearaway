"""Locator maps for the geography modules: a small regional map (US / Europe /
Africa / Americas / Asia / Oceania) with every shape outlined, so the card can
fill the target black to show where it is. Same sources as the outline data:
/tmp/us-states.json, /tmp/ne.geojson (Natural Earth 110m), /tmp/mledoze.json
(display names, so targets match countries-data.ts)."""
import json, math, os, sys
sys.setrecursionlimit(10000)
us=json.load(open('/tmp/us-states.json'))
ne=json.load(open('/tmp/ne.geojson'))
ml=json.load(open('/tmp/mledoze.json'))
name_by_cca3={c['cca3']:c['name']['common'] for c in ml}

W=300.0
def rings(g):
    polys=[g['coordinates']] if g['type']=='Polygon' else g['coordinates']
    return [p[0] for p in polys]
def rdp(pts,eps):
    if len(pts)<3: return pts
    (x1,y1),(x2,y2)=pts[0],pts[-1]; dx,dy=x2-x1,y2-y1; dmax=0; idx=0
    for i in range(1,len(pts)-1):
        x,y=pts[i]
        if dx==dy==0: d=math.hypot(x-x1,y-y1)
        else:
            t=max(0,min(1,((x-x1)*dx+(y-y1)*dy)/(dx*dx+dy*dy))); d=math.hypot(x-(x1+t*dx),y-(y1+t*dy))
        if d>dmax: dmax,idx=d,i
    return rdp(pts[:idx+1],eps)[:-1]+rdp(pts[idx:],eps) if dmax>eps else [pts[0],pts[-1]]

def projector(box,k_lat,width=W,ox=0.0,oy=0.0,wrap=False):
    lon0,lon1,lat0,lat1=box; k=math.cos(math.radians(k_lat)); s=width/((lon1-lon0)*k)
    def tf(lon,lat):
        if wrap and lon<0: lon+=360
        return (ox+(lon-lon0)*k*s, oy+(lat1-lat)*s)
    return tf,(lat1-lat0)*s

def build(features,tf,H,eps=0.6,keep_ring=None):
    """features: [(name, geom)] → [{n, d, c?}] for shapes that touch the frame."""
    out=[]
    for name,geom in features:
        subs=[]; allpts=[]
        for r in rings(geom):
            if keep_ring and not keep_ring(name,r): continue
            pts=rdp([tf(*p) for p in r],eps)
            if len(pts)<3: continue
            xs=[p[0] for p in pts]; ys=[p[1] for p in pts]
            if max(xs)<0 or min(xs)>W or max(ys)<0 or min(ys)>H: continue
            subs.append("M"+" ".join(f"{x:.1f} {y:.1f}" for x,y in pts)+"Z"); allpts+=pts
        if not subs: continue
        rec={'n':name,'d':"".join(subs)}
        xs=[p[0] for p in allpts if 0<=p[0]<=W]; ys=[p[1] for p in allpts if 0<=p[1]<=H]
        if xs and ys:
            span=max(max(xs)-min(xs),max(ys)-min(ys))
            # Tiny targets (Luxembourg, Rwanda, Rhode Island) get a ring so they're findable.
            if span<W*0.06:
                rec['c']=[round((max(xs)+min(xs))/2,1),round((max(ys)+min(ys))/2,1),round(max(9,span),1)]
        out.append(rec)
    return out

regions={}

# --- US: lower 48, with Alaska + Hawaii as bottom-left insets.
usf=[(f['properties']['name'],f['geometry']) for f in us['features'] if f['properties']['name']!='Puerto Rico']
tf48,H48=projector((-125,-66.5,24.3,49.5),37)
lower=build([x for x in usf if x[0] not in ('Alaska','Hawaii')],tf48,H48)
tfak,_=projector((-170,-129,51,71.5),62,width=72,ox=2,oy=H48-44)
ak=build([x for x in usf if x[0]=='Alaska'],tfak,H48,eps=0.4,keep_ring=lambda n,r: all(-171<p[0]<-129 for p in r))
tfhi,_=projector((-160.5,-154.6,18.8,22.4),20,width=38,ox=80,oy=H48-24)
hi=build([x for x in usf if x[0]=='Hawaii'],tfhi,H48,eps=0.3)
regions['us']={'h':round(H48,1),'shapes':lower+ak+hi}

# --- Countries.
nef=[]; region_of={}
for f in ne['features']:
    p=f['properties']; iso=p.get('ISO_A3')
    if not iso or iso=='-99': iso=p.get('ISO_A3_EH')
    disp=name_by_cca3.get(iso) or p.get('NAME')
    nef.append((disp,f['geometry']))
    cont=p.get('CONTINENT')
    region_of[disp]={'Europe':'europe','Africa':'africa','Asia':'asia','Oceania':'oceania',
                     'North America':'americas','South America':'americas'}.get(cont)
BOXES={
  'europe':((-25,45,34,71.5),52,False),
  'africa':((-19,53,-36,38.5),0,False),
  'americas':((-170,-28,-56,75),25,False),
  'asia':((25,150,-12,60),28,False),
  'oceania':((108,190,-50,2),-24,True),
}
for key,(box,k,wrap) in BOXES.items():
    tf,H=projector(box,k,wrap=wrap)
    regions[key]={'h':round(H,1),'shapes':build(nef,tf,H)}

country_names=[json.loads('"'+l.split('"')[1]+'"') for l in open('src/lib/puzzles/countries-data.ts') if l.strip().startswith('{ name:')]
missing=[]; cmap={}
for n in country_names:
    r=region_of.get(n)
    if not r or not any(s['n']==n for s in regions[r]['shapes']): missing.append(n); continue
    cmap[n]=r
state_names=[json.loads('"'+l.split('"')[1]+'"') for l in open('src/lib/puzzles/states-data.ts') if l.strip().startswith('{ name:')]
missing+=[n for n in state_names if not any(s['n']==n for s in regions['us']['shapes'])]
print("missing:",missing)
for k,v in regions.items(): print(k,'h',v['h'],'shapes',len(v['shapes']),'rings',sum(1 for s in v['shapes'] if 'c' in s))

lines=["// AUTO-GENERATED by scripts/build-locator-data.py (Natural Earth 110m + US states). Offline; no runtime fetch.",
 "export type LocatorRegion = 'us'|'europe'|'africa'|'americas'|'asia'|'oceania';",
 "/** One shape on a locator map: name, path, and a findability ring [cx, cy, r] for tiny ones. */",
 "export interface LocatorShape { n: string; d: string; c?: [number, number, number]; }",
 f"export const LOCATOR_W = {int(W)};",
 "export const LOCATOR_MAPS: Record<LocatorRegion, { h: number; shapes: LocatorShape[] }> = {"]
for k,v in regions.items():
    lines.append(f"  {k}: {{ h: {v['h']}, shapes: {json.dumps(v['shapes'],separators=(',',':'))} }},")
lines+=["};","/** Which locator map each quiz country appears on. */",
 f"export const COUNTRY_LOCATOR: Record<string, LocatorRegion> = {json.dumps(cmap,separators=(',',':'))};"]
open('src/lib/puzzles/locator-data.ts','w').write("\n".join(lines)+"\n")
print("file KB:",round(os.path.getsize('src/lib/puzzles/locator-data.ts')/1024))
